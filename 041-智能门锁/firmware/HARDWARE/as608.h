#ifndef __AS608_H
#define __AS608_H

#include "stm32f10x.h"

/*
 * ZW101 半导体射频指纹模块驱动（AS608 协议，USART2，默认 57600bps）
 * ------------------------------------------------------------------
 * 协议包格式（16 进制）：
 *   EF 01 | 地址(4B) | 包标识(1B) | 长度(2B) | 数据(nB) | 校验和(2B)
 *   - 包标识：0x01=指令包  0x07=应答包  0x08/0x09=数据/结束包
 *   - 长度 = 数据字节数 + 2（含校验和）
 *   - 校验和 = 包标识 + 长度(2B) + 数据 之和（16 位）
 *
 * 常用确认码：0x00=成功  0x01=包错误  0x02=无手指  0x03=录入失败
 */

/* 指纹库页码分配：1~48 为成员指纹，49 号页固定为"胁迫手指"
 * ------------------------------------------------------------------
 *   ★ 为什么是 48/49（2026-09-11 定案，别再随手改回去）
 *
 *   1) 本模块实际是 HLK-ZW101（半导体射频式），**容量只有 50 枚**。
 *      旧定义 USER_PAGE_MAX=99 / DURESS_PAGE=100 物理上就越界，
 *      模板永远存不进 100 号页 ⇒ 胁迫指纹有验证分支、却没模板可验证，
 *      是支**死代码**。
 *
 *   2) ★ 关键：AS608 **协议本身是 0 基页号**（官方 AS608 容量 300 →
 *      页号 0~299）。所以"容量 50 枚"的 ZW101 很可能是 **0~49**，
 *      而不是 1~50。这一点无法靠读代码确认（模块手册没留档），
 *      于是**取两种约定都合法的页号**：
 *
 *          页号 1~48   → 0 基(0~49) 合法，1 基(1~50) 也合法
 *          页号 49     → 同上，两种约定都是最后一页
 *          页号 50     → 只有 1 基才合法；若是 0 基，存进去会**直接报失败**
 *
 *      代价只是少用一个位置（50 个槽位里空出一个），
 *      换来的是"不管模块是 0 基还是 1 基都能用"。
 *      ⚠️ 若日后用 ReadSysPara(0x0F) 读到参数区确认是 1 基，
 *         可把这两个宏改成 49 / 50 多要回一个位置（改完记得同步
 *         app_ui.c 的文案和"指纹编号(1-50)"标签）。
 *
 *   配套：AS608_Identify() 的搜索范围是 USER_PAGE_MAX + 1 = 49，
 *         正好把胁迫页(49)也覆盖进去，不用改搜索代码。
 *   注：换真 AS608（容量 ≥100 枚）时改回 99/100 即可，其余不用动。 */
#define AS608_USER_PAGE_MAX   48
#define AS608_DURESS_PAGE     49

/* 返回码：负数 = 通信失败；≥0 = 模块确认码 */
#define AS608_ERR_TIMEOUT   (-1)

int      AS608_Check(void);                 /* 链路自检，1=模块应答正常 */
int      AS608_GetImage(void);              /* 采集指纹图像            */
int      AS608_GenChar(uint8_t bufid);      /* 生成特征(放入缓冲1/2)   */
int      AS608_RegModel(void);              /* 合成模板(两次特征合成)  */
int      AS608_Search(uint8_t bufid, uint16_t start_page, uint16_t count,
                      uint16_t *page_id, uint16_t *score);  /* 搜索比对 */
int      AS608_StoreChar(uint8_t bufid, uint16_t page_id);  /* 存模板   */
int      AS608_DeleteChar(uint16_t page_id, uint16_t count);/* 删模板   */
int      AS608_Empty(void);                 /* 清空指纹库              */
int      AS608_Identify(uint16_t *page_id, uint16_t *score); /* 一键识别 */

#endif
